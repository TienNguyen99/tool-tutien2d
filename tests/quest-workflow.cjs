const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({window:{}});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../extension/quest-workflow.js'),'utf8'),context);
const W=context.window.__tienloWorkflow,plan={autoChoice:'Linh Dược',craftItemId:'tu_khi_duoc'};
const button={title:'Linh Dược',textContent:'Luyện',matches:()=>true,getAttribute:()=>'',closest:()=>({querySelector:()=>({textContent:'Linh Dược'})})};
const open=W.observe(button,plan);assert.equal(open.action,'open_recipe');
assert.equal(W.evaluate(open,{count:0},{detailName:'Linh Dược',count:0}),'success','Opening detail succeeds without quest progress');
assert.equal(W.evaluate(open,{count:0},{detailName:'Tụ Khí Đan',count:0}),'pending');
button.matches=()=>false;const craft=W.observe(button,plan);
assert.equal(craft.action,'craft_item');assert.equal(W.canExecute(craft),true);
assert.equal(W.evaluate(craft,{count:0},{count:1}),'success');assert.equal(W.evaluate(craft,{count:0},{count:0}),'pending');
assert.equal(W.canExecute({...craft,name:'Tụ Khí Đan'}),false,'Never craft a mismatched recipe');
W.record('stage9',open,'success');const sequence=W.record('stage9',craft,'success');assert.equal(sequence.length,2);
assert.equal(sequence[0].action,'open_recipe');assert.equal(sequence[1].action,'craft_item');
console.log('Recipe observation, step evaluation, wrong-item guard and sequence trace passed');
for(let i=0;i<4;i++)assert.equal(W.attempt('character/stage/no-progress','Luyện'),true);
assert.equal(W.attempt('character/stage/no-progress','Luyện'),false);
assert.equal(W.attempt('character/stage/no-progress','Option khác'),true);
assert.equal(W.attempt('character/stage/progress-changed','Luyện'),true);
console.log('Four-attempt action guard and alternative action passed');
